#!/bin/bash
# ============================================================================
# xnuloader/build.sh — Build the HakiOS-x86 UEFI boot loader for x86_64
#
# This produces a UEFI PE64 application (xnuloader.efi) that can be
# loaded by OVMF in QEMU or by a real PC's UEFI firmware.
#
# We use clang for the compiler and lld-link for the linker (PE output).
# No EDK2 dependency — we write our own minimal UEFI headers.
# ============================================================================
set -e

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
ROOT_DIR="$(dirname "$SCRIPT_DIR")"
BUILD_DIR="$SCRIPT_DIR/build"

# Compiler settings
CC="${CC:-clang}"
LD="${LD:-lld-link}"

# Target: x86_64 UEFI (PE64)
CFLAGS="-target x86_64-unknown-windows-uefi \
        -ffreestanding \
        -fshort-wchar \
        -fno-stack-protector \
        -fno-exceptions \
        -Wall -Wextra \
        -O2 \
        -I$SCRIPT_DIR"

LDFLAGS="-subsystem:efi_application \
         -entry:efi_main \
         -nodefaultlib \
         -lldmap"

echo ">>> Building HakiOS-x86 boot loader (x86_64 UEFI)"
echo ">>> CC:   $CC"
echo ">>> CFLAGS: $CFLAGS"
echo ">>> LD:   $LD"
echo ""

# Create build directory
mkdir -p "$BUILD_DIR"

# ---- Compile main.c ----
echo ">>> Compiling main.c..."
"$CC" $CFLAGS -c "$SCRIPT_DIR/main.c" -o "$BUILD_DIR/main.o" || {
    echo ">>> ERROR: compilation failed."
    echo ">>> Note: you need clang with UEFI target support."
    echo ">>> Install: apt install clang lld"
    echo ""
    echo ">>> If clang doesn't support '-target x86_64-unknown-windows-uefi',"
    echo ">>> try: -target x86_64-pc-win32-coff"
    exit 1
}

# ---- Link into PE64 (EFI application) ----
echo ">>> Linking xnuloader.efi..."
"$LD" $LDFLAGS \
    -out:"$BUILD_DIR/xnuloader.efi" \
    "$BUILD_DIR/main.o" || {

    echo ">>> lld-link failed, trying direct linker approach..."

    # Alternative: use ld.lld with PE/EFI subsystem
    if command -v ld.lld &>/dev/null; then
        ld.lld -m elf_x86_64 \
            -e efi_main \
            -o "$BUILD_DIR/xnuloader.efi" \
            "$BUILD_DIR/main.o" 2>/dev/null || {

            echo ">>> ld.lld also failed. Trying objcopy approach..."

            # Last resort: link as ELF and convert to PE
            if command -v objcopy &>/dev/null; then
                ld -e efi_main -o "$BUILD_DIR/xnuloader.elf" "$BUILD_DIR/main.o" 2>/dev/null || true
                objcopy -O pei-x86-64 \
                    --set-section-flags .text=code \
                    "$BUILD_DIR/xnuloader.elf" \
                    "$BUILD_DIR/xnuloader.efi" 2>/dev/null || true
            fi
        }
    fi

    if [ ! -f "$BUILD_DIR/xnuloader.efi" ]; then
        echo ">>> ERROR: linking failed."
        echo ">>> The boot loader needs clang + lld-link (from LLVM)."
        echo ">>> Install: apt install clang lld"
        exit 1
    fi
}

echo ""
echo ">>> Boot loader built successfully!"
echo ">>> Output: $BUILD_DIR/xnuloader.efi"

# ---- Copy to prebuilt ----
mkdir -p "$ROOT_DIR/prebuilt"
cp "$BUILD_DIR/xnuloader.efi" "$ROOT_DIR/prebuilt/" 2>/dev/null || true

# ---- Create identity.h placeholder ----
# On ARM, this file contains device identity from the IPSW.
# On x86, we generate a generic PC identity.
if [ ! -f "$SCRIPT_DIR/identity.h" ]; then
    cat > "$SCRIPT_DIR/identity.h" << 'IDENTITY_EOF'
/*
 * identity.h — Generated by build.sh
 *
 * On ARM (HakiOS), this file contains iPhone device identity
 * extracted from the IPSW device tree.
 *
 * On x86_64 (HakiOS-x86), we use a generic PC identity.
 * In the full iOS user space path, this would contain a
 * model identifier that launchd expects.
 */

#ifndef _XNULOADER_IDENTITY_H_
#define _XNULOADER_IDENTITY_H_

#define HAKIOS_IDENTITY_PRODUCT_NAME  "HakiOS-x86"
#define HAKIOS_IDENTITY_MODEL        "PC-Q35"
#define HAKIOS_IDENTITY_BOARD_ID     "HakiosPC1"
#define HAKIOS_IDENTITY_CHIP_ID      0x00000000
#define HAKIOS_IDENTITY_SERIAL       "HakiOS-x86-0000"

#endif /* _XNULOADER_IDENTITY_H_ */
IDENTITY_EOF
    echo ">>> Generated identity.h (generic PC identity)"
fi

echo ""
echo ">>> Done. Copy xnuloader.efi and mach_kernel to:"
echo ">>> \\EFI\\HAKIOS\\ on your EFI System Partition"
